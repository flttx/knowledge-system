export type TranslationKey = keyof typeof messages.en;

export function normalizeLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  return value.toLowerCase().startsWith("en") ? "en" : value.toLowerCase().startsWith("zh") ? "zh-CN" : null;
}

export function localeFromAcceptLanguage(value: string | null | undefined): Locale {
  return normalizeLocale(value?.split(",")[0]) ?? DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: TranslationKey, params?: Record<string, string | number>): string {
  const localized = messages[locale] as Record<TranslationKey, string>;
  const fallback = messages[DEFAULT_LOCALE] as Record<TranslationKey, string>;
  let result = localized[key] ?? fallback[key] ?? key;
  for (const [name, value] of Object.entries(params ?? {})) result = result.replaceAll(`{${name}}`, String(value));
  return result;
}
